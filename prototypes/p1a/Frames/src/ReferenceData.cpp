BodyStateFixture parseHorizonsVectorTable(const std::filesystem::path& path)
{
    std::ifstream file(path);
    if (!file) {
        throw std::runtime_error("Horizons fixture: cannot open " + path.string());
    }

    std::vector<std::string> lines;
    std::string line;
    while (std::getline(file, line)) {
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
        }
        lines.push_back(line);
    }

    BodyStateFixture fixture;

    const std::string targetName = extractHeaderValue(lines, "Target body name");
    fixture.bodyName = targetName;
    fixture.naifId = extractNaifId(targetName);
    fixture.centreName = extractHeaderValue(lines, "Center body name");
    fixture.referenceFrame = extractHeaderValue(lines, "Reference frame");

    for (const std::string& candidate : lines) {
        if (candidate.rfind("Target body name", 0) == 0) {
            fixture.ephemerisSource = extractEphemerisSource(candidate);
            break;
        }
    }

    if (fixture.naifId == 0 || fixture.referenceFrame.empty()) {
        throw std::runtime_error("Horizons fixture " + path.string()
                                 + ": header is missing the target id or reference frame");
    }
    if (fixture.referenceFrame != "ICRF") {
        throw std::runtime_error("Horizons fixture " + path.string() + ": reference frame is '"
                                 + fixture.referenceFrame + "', expected ICRF");
    }

    // ADR 0008 requires reference states at a TDB boundary. Horizons states the units and the
    // aberration treatment in its own trailer, and both are checked rather than assumed: a
    // table generated with light-time corrections would be a physically different quantity
    // that differs by hundreds of kilometres and still parses cleanly.
    const std::string outputUnits = extractHeaderValue(lines, "Output units");
    if (outputUnits.rfind("KM-S", 0) != 0) {
        throw std::runtime_error("Horizons fixture " + path.string() + ": output units are '"
                                 + outputUnits + "', expected KM-S");
    }
    const bool geometric =
        std::any_of(lines.begin(), lines.end(), [](const std::string& candidate) {
            return candidate.find("Geometric state vectors have NO corrections") != std::string::npos;
        });
    if (!geometric) {
        throw std::runtime_error("Horizons fixture " + path.string()
                                 + ": table does not declare uncorrected geometric states");
    }

    const auto startMarker = std::find(lines.begin(), lines.end(), "$$SOE");
    const auto endMarker = std::find(lines.begin(), lines.end(), "$$EOE");
    if (startMarker == lines.end() || endMarker == lines.end() || endMarker <= startMarker + 1) {
        throw std::runtime_error("Horizons fixture " + path.string() + ": no $$SOE/$$EOE block");
    }
    if (endMarker != startMarker + 2) {
        throw std::runtime_error("Horizons fixture " + path.string()
                                 + ": expected exactly one epoch in the table");
    }

    std::vector<std::string> fields;
    std::stringstream row(*(startMarker + 1));
    std::string field;
    while (std::getline(row, field, ',')) {
        fields.push_back(field);
    }
    if (fields.size() < 8) {
        throw std::runtime_error("Horizons fixture " + path.string()
                                 + ": vector row has too few columns");
    }

    fixture.epoch = TdbEpoch::fromJulianDate(parseDouble(fields[0], path));
    fixture.calendarTdb = trim(fields[1]);
    fixture.position = PositionMetres::fromKilometres(Vec3{parseDouble(fields[2], path),
                                                           parseDouble(fields[3], path),
                                                           parseDouble(fields[4], path)});
    fixture.velocity = VelocityMetresPerSecond::fromKilometresPerSecond(
        Vec3{parseDouble(fields[5], path), parseDouble(fields[6], path),
             parseDouble(fields[7], path)});
    fixture.printedSignificantDigits = countSignificantDigits(trim(fields[2]));

    return fixture;
}

ReferenceData ReferenceData::loadFromDirectory(const std::filesystem::path& fixtureRoot,
                                               bool verifyChecksums)
{
    ReferenceData data;

    for (const ExpectedFixture& expected : kExpectedFixtures) {
        const std::filesystem::path path = fixtureRoot / expected.relativePath;
        if (!std::filesystem::exists(path)) {
            throw std::runtime_error("ReferenceData: missing fixture " + path.string());
        }

        FixtureProvenance record;
        record.fileName = expected.relativePath;
        record.role = expected.role;
        record.sourceUrl = expected.sourceUrl;
        record.expectedSha256 = expected.sha256;
        record.actualSha256 = sha256HexOfFile(path);

        if (verifyChecksums && record.actualSha256 != record.expectedSha256) {
            throw std::runtime_error("ReferenceData: " + path.string()
                                     + " has digest " + record.actualSha256 + ", expected "
                                     + record.expectedSha256
                                     + ". The fixture and the results derived from it no longer"
                                       " match; re-run the acquisition step and update the"
                                       " recorded digest deliberately.");
        }
        data.m_provenance.push_back(std::move(record));
    }

    const TextKernel leapSecondKernel =
        TextKernel::loadFromFile(fixtureRoot / "kernels/naif0012.tls");
    data.m_timeScales = TimeScales::fromLeapSecondKernel(leapSecondKernel);

    const TextKernel planetaryConstants =
        TextKernel::loadFromFile(fixtureRoot / "kernels/pck00011.tpc");
    const std::vector<double> radii = planetaryConstants.numbers("BODY399_RADII", 3);
    if (radii[0] != radii[1]) {
        throw std::runtime_error(
            "ReferenceData: BODY399_RADII is triaxial; the biaxial Ellipsoid type would silently"
            " discard the second equatorial radius");
    }
    data.m_earthEllipsoid =
        Ellipsoid::fromRadiiKilometres("IAU Earth (pck00011 BODY399_RADII)", radii[0], radii[2]);

    const std::vector<double> poleRa = planetaryConstants.numbers("BODY399_POLE_RA", 3);
    const std::vector<double> poleDec = planetaryConstants.numbers("BODY399_POLE_DEC", 3);
    const std::vector<double> primeMeridian = planetaryConstants.numbers("BODY399_PM", 3);
    for (std::size_t i = 0; i < 3; ++i) {
        data.m_poleRa[i] = poleRa[i];
        data.m_poleDec[i] = poleDec[i];
        data.m_primeMeridian[i] = primeMeridian[i];
    }

    const TextKernel gravitationalKernel =
        TextKernel::loadFromFile(fixtureRoot / "kernels/gm_de440.tpc");
    for (const int naifId : {3, 10, 301, 399}) {
        const std::string name = "BODY" + std::to_string(naifId) + "_GM";
        // km^3/s^2 to m^3/s^2 at the data boundary, once, where the unit is still visible.
        data.m_gravitationalParameters.emplace_back(naifId, gravitationalKernel.number(name) * 1e9);
    }

    for (const char* relativePath : {"horizons/ssb-sun.txt", "horizons/ssb-emb.txt",
                                     "horizons/ssb-earth.txt", "horizons/ssb-moon.txt"}) {
        data.m_bodyStates.push_back(parseHorizonsVectorTable(fixtureRoot / relativePath));
    }

    data.m_fixtureEpoch = data.m_bodyStates.front().epoch;
    for (const BodyStateFixture& state : data.m_bodyStates) {
        if (state.epoch.secondsPastJ2000() != data.m_fixtureEpoch.secondsPastJ2000()) {
            throw std::runtime_error("ReferenceData: body fixtures are at different epochs; they"
                                     " cannot be differenced into one frame graph");
        }
        if (state.centreName.rfind("Solar System Barycenter", 0) != 0) {
            throw std::runtime_error("ReferenceData: " + state.bodyName + " is centred on '"
                                     + state.centreName + "', expected the barycentre");
        }
    }

    return data;
}

double ReferenceData::gravitationalParameter(int naifId) const
{
    const auto found = std::find_if(
        m_gravitationalParameters.begin(), m_gravitationalParameters.end(),
        [naifId](const std::pair<int, double>& entry) { return entry.first == naifId; });
    if (found == m_gravitationalParameters.end()) {
        throw std::runtime_error("ReferenceData: no GM for NAIF id " + std::to_string(naifId));
    }
    return found->second;
}

const BodyStateFixture& ReferenceData::bodyState(int naifId) const
{
    const auto found = std::find_if(
        m_bodyStates.begin(), m_bodyStates.end(),
        [naifId](const BodyStateFixture& state) { return state.naifId == naifId; });
    if (found == m_bodyStates.end()) {
        throw std::runtime_error("ReferenceData: no body state for NAIF id "
                                 + std::to_string(naifId));
    }
    return *found;
}

std::filesystem::path parseFixtureRoot(int argc, char** argv)
{
    for (int i = 1; i < argc; ++i) {
        if (std::string_view{argv[i]} == "--fixtures") {
            if (i + 1 >= argc) {
                throw std::invalid_argument("--fixtures requires a directory path");
            }
            return std::filesystem::path{argv[i + 1]};
        }
    }
#ifdef SOL_PROTO_FIXTURE_ROOT
    return std::filesystem::path{SOL_PROTO_FIXTURE_ROOT};
#else
#error "SOL_PROTO_FIXTURE_ROOT is not defined; the Frames library's CMake target must define it"
#endif
}

Geodetic ReferenceData::launchAnchor() noexcept
{
    Geodetic anchor;
    anchor.latitude = Radians::fromDegrees(28.0);
    anchor.longitude = Radians::fromDegrees(-80.5);
    anchor.heightMetres = 5.0;
    return anchor;
}

