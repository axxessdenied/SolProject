/// One checked-in fixture and the digest it is expected to have.
///
/// The digests live in source rather than in a sidecar file so that changing reference data
/// forces a visible code change in the same review. A checksum manifest that travels with the
/// data it protects can be regenerated by the same command that corrupted the data.
struct ExpectedFixture {
    const char* relativePath;
    const char* role;
    const char* sourceUrl;
    const char* sha256;
};

