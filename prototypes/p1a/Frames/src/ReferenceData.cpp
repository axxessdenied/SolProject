[[nodiscard]] std::string trim(std::string_view text)
{
    const std::size_t begin = text.find_first_not_of(" \t\r\n");
    if (begin == std::string_view::npos) {
        return {};
    }
    const std::size_t end = text.find_last_not_of(" \t\r\n");
    return std::string{text.substr(begin, end - begin + 1)};
}

[[nodiscard]] double parseDouble(const std::string& token, const std::filesystem::path& path)
{
    const std::string text = trim(token);
    double value = 0.0;
    const char* first = text.data();
    const char* last = first + text.size();
    const auto [pointer, error] = std::from_chars(first, last, value);
    if (error != std::errc{} || pointer != last) {
        throw std::runtime_error("Horizons fixture " + path.string() + ": '" + text
                                 + "' is not a number");
    }
    return value;
}

/// Counts the significant decimal digits Horizons printed, so the precision budget can state
/// the resolution of its own reference data instead of assuming it is exact.
[[nodiscard]] int countSignificantDigits(std::string_view token)
{
    int digits = 0;
    bool seenNonZero = false;
    for (const char c : token) {
        if (c == 'E' || c == 'e') {
            break;
        }
        if (c >= '0' && c <= '9') {
            if (c != '0') {
                seenNonZero = true;
            }
            if (seenNonZero) {
                ++digits;
            }
        }
    }
    return digits;
}

[[nodiscard]] std::string extractHeaderValue(const std::vector<std::string>& lines,
                                             std::string_view prefix)
{
    for (const std::string& line : lines) {
        if (line.rfind(prefix, 0) == 0) {
            const std::size_t colon = line.find(':');
            if (colon != std::string::npos) {
                return trim(std::string_view{line}.substr(colon + 1));
            }
        }
    }
    return {};
}

/// Pulls the `{source: DE441}` annotation out of a Horizons header line.
[[nodiscard]] std::string extractEphemerisSource(const std::string& targetLine)
{
    const std::size_t open = targetLine.find("{source:");
    if (open == std::string::npos) {
        return "unstated";
    }
    const std::size_t close = targetLine.find('}', open);
    if (close == std::string::npos) {
        return "unstated";
    }
    return trim(std::string_view{targetLine}.substr(open + 8, close - open - 8));
}

/// Pulls the NAIF integer id out of a name like `Earth (399)`.
[[nodiscard]] int extractNaifId(const std::string& targetName)
{
    const std::size_t open = targetName.rfind('(');
    const std::size_t close = targetName.rfind(')');
    if (open == std::string::npos || close == std::string::npos || close < open) {
        return 0;
    }
    const std::string digits = trim(std::string_view{targetName}.substr(open + 1, close - open - 1));
    int value = 0;
    const auto [pointer, error] =
        std::from_chars(digits.data(), digits.data() + digits.size(), value);
    if (error != std::errc{} || pointer != digits.data() + digits.size()) {
        return 0;
    }
    return value;
}

