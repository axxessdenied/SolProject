SOL_TEST(base64DecodesKnownVectors)
{
    std::vector<std::uint8_t> out;
    SOL_CHECK(cooker::decodeBase64("aGVsbG8=", 8, out));
    SOL_CHECK(out.size() == 5 && std::memcmp(out.data(), "hello", 5) == 0);
    SOL_CHECK(cooker::decodeBase64("", 0, out) && out.empty());
    SOL_CHECK(!cooker::decodeBase64("a!b", 3, out));
}

