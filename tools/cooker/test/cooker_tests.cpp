SOL_TEST(bc1EncodesSolidBlockExactly)
{
    cooker::ImageRgba image;
    image.width = 4;
    image.height = 4;
    image.pixels.assign(64, 0);
    for (std::size_t i = 0; i < 16; ++i) {
        image.pixels[i * 4 + 0] = 255; // pure red
        image.pixels[i * 4 + 3] = 255;
    }

    const std::vector<std::uint8_t> blocks = cooker::encodeBc1(image);
    SOL_CHECK(blocks.size() == 8);
    // Both endpoints equal pure red in RGB565 (0xF800); all indices select c0.
    SOL_CHECK(blocks[0] == 0x00 && blocks[1] == 0xF8);
    SOL_CHECK(blocks[2] == 0x00 && blocks[3] == 0xF8);
    SOL_CHECK(blocks[4] == 0 && blocks[5] == 0 && blocks[6] == 0 && blocks[7] == 0);
}

